def make_template(slug, title, category, summary, target_count, items):
    if len(items) != target_count:
        raise ValueError(f"{slug} must have {target_count} items, got {len(items)}")
    if len({title for title, _category in items}) != len(items):
        raise ValueError(f"{slug} has duplicate item titles")
    return {
        "slug": slug,
        "title": title,
        "category": category,
        "summary": summary,
        "description": summary,
        "target_count": target_count,
        "items": items,
        "goals": [{"title": item_title, "category": item_category} for item_title, item_category in items],
    }


